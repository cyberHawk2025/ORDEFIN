const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('finora', Object.freeze({
  listCards: () => ipcRenderer.invoke('cards:list'),
  addCard: (card) => ipcRenderer.invoke('cards:add', card),
  identifyCard: (prefix) => ipcRenderer.invoke('cards:identify', prefix),
  updateCardIdentity: (card) => ipcRenderer.invoke('cards:updateIdentity', card),
  updateCardLimit: (card) => ipcRenderer.invoke('cards:updateLimit', card),
  deleteCard: (id) => ipcRenderer.invoke('cards:delete', id),
  updateCardMode: (card) => ipcRenderer.invoke('cards:updateMode',card),
  updateCardNumber: (card) => ipcRenderer.invoke('cards:updateNumber', card),
  payCard: (payment) => ipcRenderer.invoke('cards:pay', payment),
  listAccounts: () => ipcRenderer.invoke('accounts:list'),
  addAccount: (a) => ipcRenderer.invoke('accounts:add', a),
  updateAccount: (a) => ipcRenderer.invoke('accounts:update', a),
  setCurrentAccountBalance: (a) => ipcRenderer.invoke('accounts:setCurrentBalance', a),
  deleteAccount: (id) => ipcRenderer.invoke('accounts:delete', id),
  listCardPayments: () => ipcRenderer.invoke('cards:payments'),
  updateCardPayment: (p) => ipcRenderer.invoke('cards:paymentUpdate', p),
  deleteCardPayment: (id) => ipcRenderer.invoke('cards:paymentDelete', id),
  listTransfers: () => ipcRenderer.invoke('transfers:list'),
  addTransfer: (t) => ipcRenderer.invoke('transfers:add', t),
  listTransactions: () => ipcRenderer.invoke('transactions:list'),
  setTransactionPaid: (data) => ipcRenderer.invoke('transactions:setPaid', data),
  addTransaction: (t) => ipcRenderer.invoke('transactions:add', t),
  updateTransaction: (t) => ipcRenderer.invoke('transactions:update', t),
  deleteTransaction: (id, refundPayment=false) => ipcRenderer.invoke('transactions:delete', id, refundPayment),
  previewTransactionDeletion: (id) => ipcRenderer.invoke('transactions:deletePreview', id),
  listActivity: () => ipcRenderer.invoke('activity:list'),
  importExcel: (rows) => ipcRenderer.invoke('transactions:importExcel', rows),
  importLegacy: (rows) => ipcRenderer.invoke('transactions:importLegacy', rows),
  listBtc: () => ipcRenderer.invoke('btc:list'),
  addBtc: (snapshot) => ipcRenderer.invoke('btc:add', snapshot),
  saveBackup: () => ipcRenderer.invoke('backup:save'),
  restoreBackup: () => ipcRenderer.invoke('backup:restore')
}));

contextBridge.exposeInMainWorld('ordefinInvestments', Object.freeze({
 load: legacy => ipcRenderer.invoke('investments:load',legacy),
 complete: (id,quantity) => ipcRenderer.invoke('investments:complete',id,quantity),
 add: op => ipcRenderer.invoke('investments:add',op),
 editAmount: (id,value) => ipcRenderer.invoke('investments:editAmount',id,value),
 editDetails: (id,patch) => ipcRenderer.invoke('investments:editDetails',id,patch),
 quote: (asset,date) => ipcRenderer.invoke('investments:quote',asset,date),
 history: (asset,fromDate) => ipcRenderer.invoke('investments:history',asset,fromDate),
 manual: (asset,q) => ipcRenderer.invoke('investments:manual',asset,q),
 observe: () => ipcRenderer.invoke('investments:observe'),
 resetPortfolio: confirmation => ipcRenderer.invoke('investments:resetPortfolio', confirmation),
 deleteAsset: (key,confirmation) => ipcRenderer.invoke('investments:deleteAsset', key, confirmation),
 deleteOperation: (id,confirmation) => ipcRenderer.invoke('investments:deleteOperation', id, confirmation)
}));
